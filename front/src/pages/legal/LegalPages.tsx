function ContactChannel() {
  if (legalConfig.contactEmail) {
    return <a href={`mailto:${legalConfig.contactEmail}`}>{legalConfig.contactEmail}</a>;
  }
  return <Link to="/contact-admin">форма связи с администратором</Link>;
}

function LegalPage({ eyebrow, title, summary, children }: {
  eyebrow: string;
  title: string;
  summary: string;
  children: ReactNode;
}) {
  return (
    <main className="legal-page">
      <BackButton>← <span>Назад</span></BackButton>
      <header className="legal-page-hero">
        <span>{eyebrow}</span>
        <h1>{title}</h1>
        <p>{summary}</p>
        <small>Редакция от {legalConfig.effectiveDate}</small>
      </header>
      <div className="legal-page-content">{children}</div>
    </main>
  );
}

